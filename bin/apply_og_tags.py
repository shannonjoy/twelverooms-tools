#!/usr/bin/env python3
"""Applies the shared Open Graph / Twitter card block to every top-level
webtools page.

Before this, all 44 top-level pages had ZERO og: or twitter: tags, so a
link to any of them pasted into Facebook, LinkedIn, Slack, iMessage or
Pinterest unfurled as a bare URL with whatever the crawler could scrape,
and never with a Twelve Rooms image. This gives each one the shared card
from bin/gen_webtools_card.py plus the title/description/url tags that
make the card render at all -- an og:image with no og:title unfurls badly
on several of those crawlers, so the image alone would not have fixed it.

SCOPE: top-level *.html only. The 360-per-degree pages under
sabian-symbols/ are generated by bin/gen_sabian_pages.py and already carry
their own per-degree card; this script never touches them, and refuses to
overwrite any page that already points at a different og:image.

Every tag is derived from what is already in the page -- its <title>, its
<meta name="description">, its <link rel="canonical"> -- so there is no
second copy of the page's own copy to drift out of sync.

The block it writes is delimited by HTML comments and the script is
idempotent: run it again after editing a page's title or description and
it rewrites the block in place rather than appending a second one.

    python3 bin/apply_og_tags.py           # write
    python3 bin/apply_og_tags.py --check   # report drift, change nothing
"""

import html
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

SITE = "https://thetwelverooms.com"
CARD_URL = f"{SITE}/og/webtools.png"
CARD_ALT = ("The Twelve Rooms: free astrology tools. "
            "The whole sky, written for you.")
SITE_NAME = "The Twelve Rooms"

BEGIN = "<!-- og:begin (managed by bin/apply_og_tags.py) -->"
END = "<!-- og:end -->"

BLOCK_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END),
                      re.DOTALL)
TITLE_RE = re.compile(r"<title>(.*?)</title>", re.DOTALL | re.IGNORECASE)
DESC_RE = re.compile(
    r'<meta\s+name=["\']description["\']\s+content=["\'](.*?)["\']\s*/?>',
    re.DOTALL | re.IGNORECASE)
CANON_RE = re.compile(
    r'<link\s+rel=["\']canonical["\']\s+href=["\'](.*?)["\']\s*/?>',
    re.IGNORECASE)
OG_IMAGE_RE = re.compile(
    r'<meta\s+property=["\']og:image["\']\s+content=["\'](.*?)["\']',
    re.IGNORECASE)


def esc(s):
    """Escape for an HTML attribute. The source values come out of
    existing attributes, so they arrive already entity-encoded; unescape
    first so a title containing &amp; does not become &amp;amp;."""
    return html.escape(html.unescape(s.strip()), quote=True)


def collapse(s):
    return re.sub(r"\s+", " ", s).strip()


def build_block(title, desc, url):
    lines = [
        BEGIN,
        f'<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{esc(SITE_NAME)}">',
        f'<meta property="og:title" content="{esc(title)}">',
    ]
    if desc:
        lines.append(f'<meta property="og:description" content="{esc(desc)}">')
    lines += [
        f'<meta property="og:url" content="{esc(url)}">',
        f'<meta property="og:image" content="{CARD_URL}">',
        '<meta property="og:image:type" content="image/png">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="{esc(CARD_ALT)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{esc(title)}">',
    ]
    if desc:
        lines.append(f'<meta name="twitter:description" content="{esc(desc)}">')
    lines += [
        f'<meta name="twitter:image" content="{CARD_URL}">',
        f'<meta name="twitter:image:alt" content="{esc(CARD_ALT)}">',
        END,
    ]
    return "\n".join(lines)


def process(path, check_only):
    src = path.read_text()

    m = TITLE_RE.search(src)
    if not m:
        return "SKIP no <title>", False
    title = collapse(m.group(1))

    d = DESC_RE.search(src)
    desc = collapse(d.group(1)) if d else ""

    c = CANON_RE.search(src)
    if c:
        url = c.group(1).strip()
    else:
        slug = "" if path.name == "index.html" else "/" + path.stem
        url = SITE + (slug or "/")

    # Never clobber a page that already points somewhere else (the
    # per-degree Sabian cards, or a future dynamic /api/og route).
    existing = OG_IMAGE_RE.search(BLOCK_RE.sub("", src))
    if existing and existing.group(1) != CARD_URL:
        return f"SKIP has its own og:image ({existing.group(1)})", False

    block = build_block(title, desc, url)

    if BLOCK_RE.search(src):
        out = BLOCK_RE.sub(lambda _: block, src, count=1)
        action = "update"
    else:
        anchor = c or d or TITLE_RE.search(src)
        insert_at = anchor.end()
        out = src[:insert_at] + "\n" + block + src[insert_at:]
        action = "insert"

    if out == src:
        return "ok unchanged", False
    if not check_only:
        path.write_text(out)
    return action, True


def main():
    check_only = "--check" in sys.argv
    pages = sorted(p for p in ROOT.glob("*.html"))
    if not pages:
        print("no top-level pages found", file=sys.stderr)
        return 1

    changed = skipped = 0
    for p in pages:
        action, did = process(p, check_only)
        if action.startswith("SKIP"):
            skipped += 1
            print(f"  {p.name:48s} {action}")
        elif did:
            changed += 1
            print(f"  {p.name:48s} {action}")

    verb = "would change" if check_only else "changed"
    print(f"{len(pages)} top-level pages, {verb} {changed}, skipped {skipped}")
    if check_only and changed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
